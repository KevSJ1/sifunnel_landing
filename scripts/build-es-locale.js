function walk(node) {
  if (Array.isArray(node)) {
    return node.map(walk);
  }

  if (node && typeof node === 'object') {
    const result = {};
    for (const [key, value] of Object.entries(node)) {
      result[key] = walk(value);
    }
    return result;
  }

  if (typeof node === 'string') {
    return translations.get(node) ?? node;
  }

  return node;
}

